# Regenerates src\Captly.UI\Themes\Icons.xaml from Lucide's SVG files (ISC licence).
# Each icon becomes one StreamGeometry on Lucide's 24 px grid. Add an icon by adding it to $icons.
$ErrorActionPreference = 'Stop'
$ProgressPreference = 'SilentlyContinue'

$lucide = '1.66.0'
$icons = [ordered]@{
    General = 'sliders-vertical'; Source = 'volume-2'; Appearance = 'captions'; Position = 'pin'
    SpeechModel = 'cpu'; Transcripts = 'file-text'; Shortcuts = 'keyboard'; About = 'info'
    ChevronLeft = 'chevron-left'; ChevronRight = 'chevron-right'; ChevronDown = 'chevron-down'
    Check = 'check'; Download = 'download'; Eye = 'eye'; Folder = 'folder'; Globe = 'globe'
    Lock = 'lock'; Monitor = 'monitor'; Move = 'move'; Play = 'play'; Captions = 'captions'
}

function Convert-Element([System.Xml.XmlElement]$e) {
    function N([string]$name) { [double]::Parse($e.GetAttribute($name), [Globalization.CultureInfo]::InvariantCulture) }
    switch ($e.LocalName) {
        'path' {
            # A path may start with a relative "m", which is absolute only at its own start. Once the
            # paths are joined it would follow on from the last one, so make it absolute here.
            $d = $e.GetAttribute('d').Trim()
            if ($d -cmatch '^m\s*(-?[\d.]+)[\s,]*(-?[\d.]+)\s*(.*)$') {
                $rest = $Matches[3]
                $d = "M$($Matches[1]) $($Matches[2])" + $(if ($rest -match '^[-\d.]') { " l$rest" } elseif ($rest) { " $rest" } else { '' })
            }
            return $d
        }
        'circle' {
            $cx = N 'cx'; $cy = N 'cy'; $r = N 'r'
            return "M$($cx - $r) $cy a$r $r 0 1 0 $(2 * $r) 0 a$r $r 0 1 0 $(-2 * $r) 0 Z"
        }
        'line' { return "M$(N 'x1') $(N 'y1') L$(N 'x2') $(N 'y2')" }
        'polyline' {
            $p = $e.GetAttribute('points').Trim() -split '[\s,]+'
            $pairs = for ($i = 0; $i -lt $p.Count; $i += 2) { "$($p[$i]) $($p[$i + 1])" }
            return "M$($pairs -join ' L')"
        }
        'rect' {
            $x = N 'x'; $y = N 'y'; $w = N 'width'; $h = N 'height'
            $r = if ($e.HasAttribute('rx')) { N 'rx' } else { 0 }
            if ($r -eq 0) { return "M$x $y h$w v$h h$(-$w) Z" }
            $iw = $w - 2 * $r; $ih = $h - 2 * $r
            return "M$($x + $r) $y h$iw a$r $r 0 0 1 $r $r v$ih a$r $r 0 0 1 $(-$r) $r h$(-$iw) a$r $r 0 0 1 $(-$r) $(-$r) v$(-$ih) a$r $r 0 0 1 $r $(-$r) Z"
        }
        default { throw "Unhandled SVG element: $($e.LocalName)" }
    }
}

$lines = @(
    '<!-- Generated by scripts/gen-icons.ps1 from Lucide. Edit that script, not this file. -->'
    '<ResourceDictionary xmlns="http://schemas.microsoft.com/winfx/2006/xaml/presentation"'
    '                    xmlns:x="http://schemas.microsoft.com/winfx/2006/xaml">'
)
foreach ($key in $icons.Keys) {
    $svg = [xml](Invoke-WebRequest -UseBasicParsing "https://raw.githubusercontent.com/lucide-icons/lucide/$lucide/icons/$($icons[$key]).svg").Content
    $data = ($svg.DocumentElement.ChildNodes | Where-Object { $_ -is [System.Xml.XmlElement] } | ForEach-Object { Convert-Element $_ }) -join ' '
    $lines += "    <StreamGeometry x:Key=`"Icon.$key`">$data</StreamGeometry>"
}
$lines += '</ResourceDictionary>'

$output = Join-Path (Split-Path $PSScriptRoot) 'src\Captly.UI\Themes\Icons.xaml'
New-Item -ItemType Directory -Force (Split-Path $output) | Out-Null
[IO.File]::WriteAllLines($output, $lines, (New-Object Text.UTF8Encoding($false)))
"$($icons.Count) icons written"
